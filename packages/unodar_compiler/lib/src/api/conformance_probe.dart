import '../runtime/runtime_files.dart';
import 'api_registry.dart';

/// A C++ file that checks bindings against their headers at compile time (docs/DECISIONS.md, Phase 6 step 11).
///
/// For every class it calls each bound method (and the constructor) with arguments of exactly the declared C++
/// parameter types (`@CppType`, or the C++ type of the Dart type), inside `decltype`, so nothing runs and nothing
/// links. A binding that names no such overload, or an ambiguous one, fails to compile. Where the binding declares
/// the C++ result type (`@CppType` on the method, or a `double`/`bool`/`void` result), a `static_assert` checks that
/// the call has exactly that type. AVR has no `<type_traits>`, so the probe brings its own `unodar_probe_same`.
///
/// A library wrapper's constant with a `@CppName` (`MSBFIRST`) must have the value of that C++ name. Shim headers
/// (`unodar_spi.h`) are included from the sketch folder: the caller writes [runtimeFiles] next to the probe.
///
/// A `@CppPrint` class must derive from Arduino's `Print`.
///
/// Printing methods (`Serial.print`, whose argument is any printable value) are skipped: their overload is chosen
/// per argument by the compiler (docs/SUBSET.md "Serial").
String conformanceProbe(ApiBindings bindings, {List<String> headers = const []}) {
  final out = StringBuffer()
    ..writeln('// Conformance probe generated by unodar: each binding against its C++ header.')
    ..writeln('#include <Arduino.h>');
  for (final header in {
    ...headers,
    for (final c in bindings.classes)
      if (c.header != null) c.header!
  }) {
    out.writeln(runtimeFiles.containsKey(header) ? '#include "$header"' : '#include <$header>');
  }
  out
    ..writeln()
    ..writeln('template <typename A, typename B> struct unodar_probe_same { static constexpr bool value = false; };')
    ..writeln('template <typename A> struct unodar_probe_same<A, A> { static constexpr bool value = true; };')
    ..writeln('// Declared, never defined: only used inside decltype, so it never runs.')
    ..writeln('template <typename T> T unodar_probe_value();')
    ..writeln('// Size 1 for a pointer to a class derived from Print, 2 for anything else.')
    ..writeln('char unodar_probe_print(const Print *);')
    ..writeln('int unodar_probe_print(...);');
  for (final constant in bindings.constants) {
    if (!constant.isNamed) continue;
    out
      ..writeln()
      ..writeln('static_assert(${constant.cppName} == ${constant.value},')
      ..writeln(
          '              "${constant.dartName}: the C++ value of ${constant.cppName} is not ${constant.value}");');
  }
  for (final cls in bindings.classes) {
    out
      ..writeln()
      ..writeln('// ${cls.dartName} → ${cls.cppName}');
    final object = bindings.objects.where((o) => o.className == cls.dartName).firstOrNull;
    final receiver = object?.cppName ?? 'unodar_probe_value<${cls.cppName} &>()';
    if (cls.isPrint) {
      // @CppPrint: print/println are Print's, so the class must convert to `Print &`.
      out
        ..writeln('static_assert(sizeof(unodar_probe_print(static_cast<${cls.cppName} *>(nullptr))) == 1,')
        ..writeln('              "${cls.dartName}: @CppPrint, but ${cls.cppName} does not derive from Print");');
    }
    if (cls.constructor case final parameters?) {
      out
        ..writeln('static_assert(sizeof(decltype(${cls.cppName}(${_arguments(parameters)}))) > 0,')
        ..writeln('              "${cls.dartName}(…): no constructor of ${cls.cppName} takes these parameter types");');
    }
    for (final method in cls.methods) {
      if (method.parameters.any((p) => p.isPrintable)) continue;
      final call = '$receiver.${method.cppName}(${_arguments(method.parameters)})';
      final expected = method.cppReturnType ?? (method.returnType.name == 'void_' ? 'void' : null);
      if (expected == null) {
        // The result type is not declared (an int without @CppType, converted to int32_t): check the call only.
        out
          ..writeln('static_assert(sizeof(decltype($call)) > 0,')
          ..writeln('              "${cls.dartName}.${method.dartName}: no overload takes these parameter types");');
      } else {
        out
          ..writeln('static_assert(unodar_probe_same<decltype($call), $expected>::value,')
          ..writeln('              "${cls.dartName}.${method.dartName}: the call does not have the declared C++ type '
              '$expected");');
      }
    }
  }
  out
    ..writeln()
    ..writeln('void setup() {}')
    ..writeln()
    ..writeln('void loop() {}');
  return out.toString();
}

String _arguments(List<ApiParameter> parameters) =>
    parameters.map((p) => 'unodar_probe_value<${p.cppType}>()').join(', ');
