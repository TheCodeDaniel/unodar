import 'package:test/test.dart';
import 'package:unodar_compiler/src/emitter/emitter.dart';
import 'package:unodar_compiler/src/ir/ir.dart';

void main() {
  // Hand-built IR for examples/blink: the emitter is tested without the analyzer, which is the point of the IR seam.
  final blink = IrProgram(
    sourceName: 'blink.dart',
    functions: [
      IrFunction(name: 'setup', line: 3, body: [
        IrCall('pinMode', [IrIntLiteral(13), IrConstant('OUTPUT')], line: 4)
      ]),
      IrFunction(
        name: 'loop',
        line: 7,
        body: [
          IrCall('digitalWrite', [IrIntLiteral(13), IrConstant('HIGH')], line: 8),
          IrCall('delay', [IrIntLiteral(500)], line: 9),
          IrCall('digitalWrite', [IrIntLiteral(13), IrConstant('LOW')], line: 10),
          IrCall('delay', [IrIntLiteral(500)], line: 11),
        ],
      ),
    ],
  );

  test('emits the PRD §9.3 shape with a #line before every function and statement', () {
    expect(const CppEmitter(UnoTarget()).emit(blink), '''
// Generated by unodar from blink.dart. Do not edit; change the Dart source instead.
#include <Arduino.h>

#line 3 "blink.dart"
void setup() {
#line 4 "blink.dart"
  pinMode(13, OUTPUT);
}

#line 7 "blink.dart"
void loop() {
#line 8 "blink.dart"
  digitalWrite(13, HIGH);
#line 9 "blink.dart"
  delay(500);
#line 10 "blink.dart"
  digitalWrite(13, LOW);
#line 11 "blink.dart"
  delay(500);
}
''');
  });

  test('an empty body emits an empty block', () {
    final program = IrProgram(sourceName: 'e.dart', functions: [IrFunction(name: 'loop', line: 1, body: [])]);
    expect(const CppEmitter(UnoTarget()).emit(program), endsWith('#line 1 "e.dart"\nvoid loop() {\n}\n'));
  });

  test('file names are escaped inside #line string literals', () {
    final program =
        IrProgram(sourceName: r'we"ird\name.dart', functions: [IrFunction(name: 'loop', line: 1, body: [])]);
    expect(const CppEmitter(UnoTarget()).emit(program), contains(r'#line 1 "we\"ird\\name.dart"'));
  });

  test('UnoTarget describes the Arduino Uno', () {
    const target = UnoTarget();
    expect(target.fqbn, 'arduino:avr:uno');
    expect(target.includes, ['Arduino.h']);
  });
}
