int32_t pulseLength(int32_t i, float scale);

#line 3 "p.dart"
constexpr int32_t ledPin = 13;
#line 4 "p.dart"
const uint8_t limit = 9;
#line 5 "p.dart"
int32_t extra = 0;

#line 7 "p.dart"
int32_t pulseLength(int32_t i, float scale) {
#line 8 "p.dart"
  return unodar_mod(i, 2) == 0 ? 150 : 450;
}

#line 10 "p.dart"
void setup() {
#line 11 "p.dart"
  int32_t n = 0;
#line 12 "p.dart"
  int32_t m;
#line 13 "p.dart"
  for (int32_t k = 0; k < 3; k++, n += 2) {
#line 14 "p.dart"
    if (k == 1) {
#line 15 "p.dart"
      continue;
    }
#line 16 "p.dart"
    pulseLength(k, 1.0f);
  }
#line 18 "p.dart"
  for (;;) {
#line 19 "p.dart"
    break;
  }
#line 21 "p.dart"
  while (n < extra) {
#line 22 "p.dart"
    n--;
  }
#line 24 "p.dart"
  if (extra > 3) {
#line 25 "p.dart"
    extra = 0;
  } else if (extra == 1) {
#line 27 "p.dart"
    extra -= 1;
  } else {
#line 29 "p.dart"
    extra = extra + 1;
  }
#line 31 "p.dart"
  {
#line 32 "p.dart"
    constexpr bool q = t;
  }
#line 34 "p.dart"
  return;
}
''');
  });
}
