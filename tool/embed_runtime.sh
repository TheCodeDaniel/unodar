#!/usr/bin/env bash
# Embeds the hand-written widget runtime header (runtime/unodar_widgets.h) in the compiler as a Dart string, so that
# `unodar build` can write it next to a widget program without finding the repo on disk (docs/DECISIONS.md, PRD 13.2).
#
# Writes packages/unodar_compiler/lib/src/runtime/unodar_widgets_header.dart. Run it after every change to the
# header; test/unit/runtime_header_test.dart fails while the embedded copy differs.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
header="$root/runtime/unodar_widgets.h"
out="$root/packages/unodar_compiler/lib/src/runtime/unodar_widgets_header.dart"
if grep -q "'''" "$header"; then
  echo "error: $header contains ''' and cannot be embedded in a raw Dart string" >&2
  exit 2
fi
mkdir -p "$(dirname "$out")"
{
  echo '// GENERATED by tool/embed_runtime.sh from runtime/unodar_widgets.h; do not edit by hand.'
  echo '// test/unit/runtime_header_test.dart fails if this copy differs from the header.'
  echo
  echo '/// The text of `runtime/unodar_widgets.h`, the widget runtime every widget program includes.'
  printf "const unodarWidgetsHeader = r'''"
  cat "$header"
  echo "''';"
} > "$out"
echo "wrote $out"
