#!/usr/bin/env bash
# Embeds the hand-written runtime headers (runtime/unodar_*.h) in the compiler as Dart strings, so that
# `unodar build` can write them next to a program without finding the repo on disk (docs/DECISIONS.md, PRD 13.2).
#
# Writes packages/unodar_compiler/lib/src/runtime/<header>_header.dart for each header, e.g. unodar_widgets.h becomes
# unodar_widgets_header.dart with `const unodarWidgetsHeader`. Run it after every change to a header;
# test/unit/runtime_header_test.dart fails while an embedded copy differs.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
for header in "$root"/runtime/unodar_*.h; do
  name="$(basename "$header" .h)"
  # unodar_widgets -> unodarWidgetsHeader
  constant="$(echo "$name" | awk -F_ '{ out = $1; for (i = 2; i <= NF; i++) out = out toupper(substr($i, 1, 1)) substr($i, 2); print out "Header" }')"
  out="$root/packages/unodar_compiler/lib/src/runtime/${name}_header.dart"
  if grep -q "'''" "$header"; then
    echo "error: $header contains ''' and cannot be embedded in a raw Dart string" >&2
    exit 2
  fi
  mkdir -p "$(dirname "$out")"
  {
    echo "// GENERATED by tool/embed_runtime.sh from runtime/$name.h; do not edit by hand."
    echo '// test/unit/runtime_header_test.dart fails if this copy differs from the header.'
    echo
    echo "/// The text of \`runtime/$name.h\`."
    echo "const $constant ="
    printf "    r'''"
    cat "$header"
    echo "''';"
  } > "$out"
  echo "wrote $out"
done
